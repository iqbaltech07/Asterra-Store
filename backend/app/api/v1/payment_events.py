# Admin Management Endpoints
# -------------------------------------------------------------
@router.get("/admin/payment-events", summary="List DANA payment events for Admin verification")
def list_payment_events(
    request: Request,
    status: Optional[str] = None,
    page: int = 1,
    limit: int = 50,
):
    get_current_admin(request)
    return PaymentEventService.get_events(status=status, page=page, limit=limit)

@router.get("/admin/payment-events/{event_id}", summary="Get payment event details by ID")
def get_payment_event_detail(event_id: str, request: Request):
    get_current_admin(request)
    event = PaymentEventService.get_event_by_id(event_id)
    if not event:
        raise HTTPException(status_code=404, detail="Payment event tidak ditemukan.")
    return {"success": True, "data": event}

@router.post("/admin/payment-events/{event_id}/confirm", summary="Admin confirms DANA payment to PAID")
def confirm_payment_event(event_id: str, payload: ConfirmEventPayload, request: Request):
    admin = get_current_admin(request)
    try:
        res = PaymentEventService.confirm_payment_event(
            event_id=event_id,
            admin_user=admin,
            order_id=payload.order_id,
            notes=payload.notes,
        )
        return res
    except ValueError as ve:
        raise HTTPException(status_code=400, detail=str(ve))
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))

@router.post("/admin/payment-events/{event_id}/reject", summary="Admin rejects DANA payment event")
def reject_payment_event(event_id: str, payload: RejectEventPayload, request: Request):
    admin = get_current_admin(request)
    try:
        res = PaymentEventService.reject_payment_event(
            event_id=event_id,
            admin_user=admin,
            reason=payload.reason,
        )
        return res
    except ValueError as ve:
        raise HTTPException(status_code=400, detail=str(ve))
    except Exception as e:
        raise HTTPException(status_code=500, detail=str(e))
